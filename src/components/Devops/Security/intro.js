// =============================================================================
// DEVOPS SECURITY BASICS
// =============================================================================

// -----------------------------------------------------------------------------
// ! PHASE 1 - WHAT SECURITY MEANS IN DEVOPS
// -----------------------------------------------------------------------------
/*
 * Security in DevOps is not one final checklist item.
 *
 * It runs through:
 * - infrastructure
 * - deployment
 * - secrets
 * - access control
 * - networking
 * - monitoring
 * - backup and recovery
 *
 * Real security is operational, not decorative.
 */

// -----------------------------------------------------------------------------
// ! PHASE 2 - WHY SECURITY MATTERS
// -----------------------------------------------------------------------------
/*
 * Production systems face risks like:
 * - leaked credentials
 * - overly broad permissions
 * - exposed ports
 * - vulnerable dependencies
 * - weak SSH access
 * - poor backup strategy
 *
 * Security incidents are often not caused by one dramatic hack.
 * They are often caused by weak everyday practices.
 */

// -----------------------------------------------------------------------------
// ! PHASE 3 - CORE SECURITY PRINCIPLES
// -----------------------------------------------------------------------------
/*
 * Good security posture means:
 * - least privilege
 * - secure defaults
 * - auditability
 * - defense in depth
 * - fast recovery
 *
 * These principles matter more than memorizing one tool.
 */

// -----------------------------------------------------------------------------
// ! PHASE 4 - DEFENSE IN DEPTH
// -----------------------------------------------------------------------------
/*
 * Defense in depth means:
 * do not rely on one protective layer only.
 *
 * Example:
 * - IAM permissions
 * - network restrictions
 * - app authentication
 * - logging and alerting
 * - backup strategy
 *
 * If one layer fails,
 * other layers still reduce damage.
 */

// -----------------------------------------------------------------------------
// ! PHASE 5 - SECURITY IS PART OF DELIVERY
// -----------------------------------------------------------------------------
/*
 * DevOps security is not about slowing everything down.
 *
 * It is about building delivery systems
 * that are safe enough to trust.
 *
 * Secure automation is stronger than insecure speed.
 */

// -----------------------------------------------------------------------------
// ! PHASE 6 - SHARED RESPONSIBILITY
// -----------------------------------------------------------------------------
/*
 * In cloud and DevOps work,
 * security is shared across layers.
 *
 * Example:
 * - cloud provider secures the platform
 * - you secure your configurations and workloads
 *
 * Managed service does not mean "security is automatic."
 */

// -----------------------------------------------------------------------------
// ! PHASE 7 - EVERYDAY SECURITY AREAS
// -----------------------------------------------------------------------------
/*
 * Everyday DevOps security work usually includes:
 * - access review
 * - secret handling
 * - patching
 * - hardening
 * - vulnerability scanning
 * - log review
 * - backup verification
 */

// -----------------------------------------------------------------------------
// ! PHASE 8 - WHY RECOVERY IS ALSO SECURITY
// -----------------------------------------------------------------------------
/*
 * Security is not only prevention.
 * It is also recovery.
 *
 * If a credential leaks,
 * if data is deleted,
 * or if ransomware-like damage happens,
 * recovery speed becomes part of your security posture.
 */

// -----------------------------------------------------------------------------
// ! FINAL TAKEAWAY
// -----------------------------------------------------------------------------
/*
 * Good DevOps security is about reducing blast radius,
 * improving visibility,
 * and recovering fast when something goes wrong.
 */
