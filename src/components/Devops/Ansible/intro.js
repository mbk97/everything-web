// =============================================================================

// -----------------------------------------------------------------------------
// ! PHASE 1 - WHAT ANSIBLE IS
// -----------------------------------------------------------------------------
/*
 * Ansible is a configuration management and automation tool.
 *
 * It helps automate repetitive server tasks like:
 * - package installation
 * - user setup
 * - config management
 * - service restarts
 */

// -----------------------------------------------------------------------------
// ! PHASE 2 - THE PROBLEM IT SOLVES
// -----------------------------------------------------------------------------
/*
 * Manual SSH work becomes painful when:
 * - you have multiple servers
 * - setup steps are repeated often
 * - environments must stay consistent
 * - people forget exact commands
 *
 * Think:
 * repeating SSH commands by hand -> Ansible playbooks
 */

// -----------------------------------------------------------------------------
// ! PHASE 3 - WHY IT FITS YOUR DEVOPS PATH
// -----------------------------------------------------------------------------
/*
 * You already have Linux and server deployment knowledge.
 *
 * Ansible helps you turn:
 * "I know the setup steps"
 * into
 * "I can automate the setup steps repeatedly."
 */

// -----------------------------------------------------------------------------
// ! PHASE 4 - AGENTLESS IDEA
// -----------------------------------------------------------------------------
/*
 * One beginner-friendly Ansible advantage:
 * it commonly works over SSH without a heavy agent model.
 *
 * That makes it approachable for Linux server automation.
 */

// -----------------------------------------------------------------------------
// ! PHASE 5 - IDEMPOTENCY
// -----------------------------------------------------------------------------
/*
 * One very important Ansible idea is idempotency.
 *
 * Meaning:
 * you should be able to run the automation again
 * and not break the server or repeat unnecessary changes.
 *
 * This makes automation safer and more predictable.
 */

// -----------------------------------------------------------------------------
// ! PHASE 6 - WHERE ANSIBLE SHINES
// -----------------------------------------------------------------------------
/*
 * Ansible is especially strong for:
 * - server bootstrap
 * - package setup
 * - user and SSH management
 * - config file deployment
 * - service management
 *
 * It is less about packaging apps,
 * and more about shaping server state.
 */

// -----------------------------------------------------------------------------
// ! FINAL TAKEAWAY
// -----------------------------------------------------------------------------
/*
 * Ansible is one of the clearest tools
 * for moving from manual operations
 * to repeatable server administration.
 */
